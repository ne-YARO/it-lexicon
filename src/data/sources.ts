/** Группы источников со сквозной нумерацией всех позиций списка */
export const SOURCE_GROUPS: NumberedSourceGroup[] = (() => {
  let counter = 1;
  return RAW_GROUPS.map((group) => ({
    ...group,
    items: group.items.map((item) => ({ ...item, num: counter++ })),
  }));
})();

/** Общее число источников в списке */
export const SOURCE_TOTAL = SOURCE_GROUPS.reduce(
  (acc, group) => acc + group.items.length,
  0
);
