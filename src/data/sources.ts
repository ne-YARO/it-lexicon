/**
 * Список источников словаря-справочника.
 *
 * Библиографические описания составлены по ГОСТ Р 7.0.100-2018
 * «Библиографическая запись. Библиографическое описание».
 * Для электронных ресурсов приводятся URL и дата обращения.
 */

export interface SourceItem {
  /** Библиографическое описание источника (без URL и даты обращения) */
  text: string;
  /** Адрес электронного ресурса, если источник сетевой */
  url?: string;
  /** Дата обращения к электронному ресурсу (ДД.ММ.ГГГГ) */
  accessed?: string;
}

export interface SourceGroup {
  /** Название тематической группы источников */
  title: string;
  /** Ключ иконки из map в компоненте Sources */
  icon: "book" | "library" | "scroll" | "globe";
  items: SourceItem[];
}

/** Статья списка с порядковым номером */
export interface NumberedSourceItem extends SourceItem {
  num: number;
}

/** Группа источников с пронумерованными позициями */
export interface NumberedSourceGroup extends SourceGroup {
  items: NumberedSourceItem[];
}

